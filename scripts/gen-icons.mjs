#!/usr/bin/env node
/** Generate the used Iconify subset and site icons from installed local data only. */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getIconData, iconToSVG, iconToHTML } from '@iconify/utils'
import sharp from 'sharp'
import { format } from 'prettier'
import prettierConfig from '../prettier.config.js'
import { site } from '../src/data/site.js'

const require = createRequire(import.meta.url)
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const names = [
  ...new Set([
    ...Object.values(site.icons),
    ...site.sections.skills.groups.flatMap((g) => g.stack.map((t) => t.icon)),
    ...site.sections.contact.links.map((link) => link.icon),
  ]),
]
  .filter(Boolean)
  .sort()
const registry = {}
const sets = new Map()
for (const name of names) {
  const [prefix, key] = name.split(':')
  if (!sets.has(prefix)) sets.set(prefix, require(`@iconify-json/${prefix}/icons.json`))
  const data = getIconData(sets.get(prefix), key)
  if (!data) throw new Error(`Missing local Iconify data: ${name}`)
  registry[name] = data
}
await writeFile(
  resolve(root, 'src/data/icons.js'),
  await format(
    '// Generated by npm run icons. Do not edit manually.\nexport const icons = ' +
      JSON.stringify(registry, null, 2),
    { ...prettierConfig, parser: 'babel' },
  ),
)
const code = iconToSVG(registry[site.icons.favicon], { width: 32, height: 32 })
const symbol = iconToHTML(code.body, { ...code.attributes, x: 8, y: 8, color: '#22c55e' })
const favicon = `<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48"><rect width="48" height="48" rx="8" fill="#0f172a"/>${symbol}</svg>\n`
await writeFile(resolve(root, 'public/favicon.svg'), favicon)
await sharp(Buffer.from(favicon))
  .resize(180, 180)
  .png()
  .toFile(resolve(root, 'public/apple-touch-icon.png'))
let notices =
  '# Icon sources and licenses\n\nGenerated from installed Iconify collection packages. Only the configured icon subset is shipped.\n\n'
for (const prefix of [...sets.keys()].sort()) {
  const info = require(`@iconify-json/${prefix}/info.json`)
  if (prefix === 'hugeicons')
    info.license.url = 'https://github.com/hugeicons/hugeicons-react/blob/main/LICENSE.md'
  const licenseText = await readFile(
    resolve(root, 'scripts/icon-licenses', prefix + '.txt'),
    'utf8',
  )
  notices +=
    `## ${info.name}\n\nAuthor: ${info.author.name}\n\nSource: ${info.author.url || 'https://icon-sets.iconify.design/' + prefix + '/'}\n\nLicense: ${info.license.title}\n\nLicense reference: ${info.license.url || info.author.url}\n\nIcons: ${names.filter((name) => name.startsWith(prefix + ':')).join(', ')}\n\n` +
    '```text\n' +
    licenseText.trim() +
    '\n```\n\n'
}
notices = notices.trimEnd() + '\n'
await mkdir(resolve(root, 'docs'), { recursive: true })
await writeFile(resolve(root, 'docs/icon-licenses.md'), notices)
await writeFile(resolve(root, 'public/icon-licenses.txt'), notices)
console.log(
  `Generated ${names.length} offline icons, favicon, apple-touch icon, and license notices.`,
)
